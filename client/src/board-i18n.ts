type ReasonKey = `board.reason.${BoardResultReason}`;

function reasonEntries(labels: Record<BoardResultReason, string>): Record<ReasonKey, string> {
  return Object.fromEntries(Object.entries(labels).map(([reason, label]) => [`board.reason.${reason}`, label])) as
    Record<ReasonKey, string>;
}

